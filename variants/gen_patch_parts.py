"""Variant catalog of the compiled patch parts (tools/android/build_patch_parts.py): one group per part file.

    variants/gen_patch_parts.py --main-repo <main project checkout> [--eboot out/eboot.elf] [--check variants/patch-parts.txt] > variants/patch-parts.txt

The parts are what the loader applies at start-up (probe.c, --patches): effect switches, model LOD, scene resolution, heaps, the cheat
hooks (new code in the cave at the end of the code segment). The catalog holds addresses and the patch bytes only. Alternatives of one
setting (effect_dof=0 / effect_dof=1, model_lod=*) share an `excl` set. Needs the eboot only because build_patch_parts.py does.
"""
import argparse
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

import _mainrepo

ROOT = None  # the main project (--main-repo)
CAVE_LO, CAVE_HI = 0x50d9700, 0x50da000   # the cheats' code (build_patch_parts.CAVE): new code, no function covers it


def read_part(path):
    data = path.read_bytes()
    magic, base, count = struct.unpack_from('<8sQQ', data, 0)
    assert magic == b'BBPATCH2', path
    pos, out = 24, []
    for _ in range(count):
        offset, length = struct.unpack_from('<QQ', data, pos)
        pos += 16
        out.append((offset, data[pos:pos + length]))
        pos += length
    assert pos == len(data), path
    return out


def excl_of(stem):
    m = re.match(r'(.+?)=', stem)
    if m:
        return m.group(1)
    return ''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    _mainrepo.add_argument(ap)
    ap.add_argument('--eboot', type=Path, help='default: <main repo>/out/eboot.elf')
    ap.add_argument('--xml', type=Path, help='default: <main repo>/patches/Bloodborne.xml')
    ap.add_argument('--check', type=Path, help='compare with this catalog file and exit 1 when it differs')
    args = ap.parse_args()
    global ROOT
    ROOT = _mainrepo.require(args.main_repo)
    args.eboot = args.eboot or ROOT / 'out/eboot.elf'
    args.xml = args.xml or ROOT / 'patches/Bloodborne.xml'
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, str(ROOT / 'tools/android/build_patch_parts.py'), '--out', tmp, '--eboot', str(args.eboot),
                        '--xml', str(args.xml)], check=True, stdout=subprocess.DEVNULL)
        out = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by variants/gen_patch_parts.py from tools/android/build_patch_parts.py: do not edit.',
               '# One group per patch part (the --patches files of tools/android/run-bionic.sh); w = patched code, c = new code (the cheats\' cave).']
        for part in sorted(Path(tmp).glob('*.bin')):
            writes = read_part(part)
            if not writes:
                continue
            stem = part.stem
            # `=0` of an effect switch with nothing to write has no file content; `=1`/`=0` pairs are alternatives
            ex = excl_of(stem)
            out.append('')
            out.append(f'group part:{stem}' + (f' excl={ex}' if ex else ''))
            for offset, data in writes:
                kind = 'c' if CAVE_LO <= offset < CAVE_HI else 'w'
                out.append(f'{kind} {offset:x} {data.hex()}')
    text = '\n'.join(out) + '\n'
    if args.check:
        if args.check.read_text() != text:
            print(f'{args.check} is out of date: rerun variants/gen_patch_parts.py', file=sys.stderr)
            sys.exit(1)
        return
    sys.stdout.write(text)


if __name__ == '__main__':
    main()
